"""Synthetic screening, grader v2 vs v3: rejected seeds and the factor distribution of the accepted set.

results/synth_v2/{index,rejected}.json: the v2 generator run (python3 src/synth/make_tasks.py 160 with the
grader at a898e10, regenerated byte-identical to the original run); tasks_synth/: the v3 run.
    python3 src/synth/screening_report.py      # writes results/synth_screening_v3.json
"""
import json
from collections import Counter
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
v2=json.load(open(ROOT / 'results/synth_v2/index.json')); v3=json.load(open(ROOT / 'tasks_synth/index.json'))
r2=json.load(open(ROOT / 'results/synth_v2/rejected.json')); r3=json.load(open(ROOT / 'tasks_synth/rejected.json'))
def dist(idx):
    occ=np.array([s['factors']['occlusion_pct'] for s in idx]); area=np.array([s['factors']['target_area_px'] for s in idx])
    bins=[0,1,10,25,50,101]; h=np.histogram(occ,bins)[0]
    return dict(n=len(idx), occ_mean=round(float(occ.mean()),1), occ_median=round(float(np.median(occ)),1),
                occ_hist={f'{a}-{b}%':int(c) for a,b,c in zip(bins[:-1],bins[1:],h)},
                occ_ge25=int((occ>=25).sum()), area_median=int(np.median(area)),
                first_seed=sum(s['synth']['attempts']==1 for s in idx),
                by_motion_attempts={m:round(float(np.mean([s['synth']['attempts'] for s in idx if s['synth']['motion']==m])),2) for m in sorted({s['synth']['motion'] for s in idx})})
out=dict(v2=dist(v2), v3=dist(v3),
         rejected=dict(v2=len(r2), v3=len(r3), v2_by=dict(Counter('+'.join(x['failed']) for x in r2)), v3_by=dict(Counter('+'.join(x['failed']) for x in r3)),
                       v2_rej_occ_mean=round(float(np.mean([x['factors']['occlusion_pct'] for x in r2])),1),
                       v3_rej_occ_mean=round(float(np.mean([x['factors']['occlusion_pct'] for x in r3])),1)),
         v2_rejected_seeds_now_accepted=len({x['seed'] for x in r2}&{s['synth']['scene_seed'] for s in v3}),
         admission=dict(G2b_dropped=sum('G2b' in s.get('dropped',[]) for s in v3), G2c_dropped=sum('G2c' in s.get('dropped',[]) for s in v3),
                        G2b_dropped_occ_mean=round(float(np.mean([s['factors']['occlusion_pct'] for s in v3 if 'G2b' in s.get('dropped',[])])),1),
                        G2b_kept_occ_mean=round(float(np.mean([s['factors']['occlusion_pct'] for s in v3 if 'G2b' not in s.get('dropped',[])])),1),
                        G2c_dropped_by_motion=dict(Counter(s['synth']['motion'] for s in v3 if 'G2c' in s.get('dropped',[]))),
                        G2b_dropped_by_motion=dict(Counter(s['synth']['motion'] for s in v3 if 'G2b' in s.get('dropped',[])))))
json.dump(out,open(ROOT / 'results/synth_screening_v3.json', 'w'),indent=1); print(json.dumps(out,indent=1))
